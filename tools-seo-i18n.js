// Auto-detect current tool key based on URL pathname
function detectCurrentToolKey() {
  const path = window.location.pathname;
  let filename = path.substring(path.lastIndexOf('/') + 1).replace('.html', '').toLowerCase();
  if (!filename || filename === 'index') filename = 'compress';
  return filename;
}

window.getSeoDictionary = function(toolKey, lang) {
  const key = toolKey || detectCurrentToolKey();
  if (window.toolsSeo && window.toolsSeo[key]) {
    return window.toolsSeo[key][lang] || window.toolsSeo[key]['en'] || {};
  }
  return {};
};

window.mergeSeoIntoCommonFooter = function() {
  if (!window.commonFooter) window.commonFooter = {};
  const currentTool = detectCurrentToolKey();
  const toolData = window.toolsSeo && window.toolsSeo[currentTool];
  if (toolData) {
    const languages = ['en', 'fr', 'es', 'de', 'pt', 'it', 'pl', 'ar'];
    languages.forEach(lang => {
      if (!window.commonFooter[lang]) window.commonFooter[lang] = {};
      if (toolData[lang]) {
        Object.assign(window.commonFooter[lang], toolData[lang]);
      }
    });
  }
};

// Merge on load and DOMContentLoaded
window.mergeSeoIntoCommonFooter();
document.addEventListener('DOMContentLoaded', window.mergeSeoIntoCommonFooter);

